// Refreshes public repository metadata for the projects listed in
// src/content/projects.ts and writes src/content/generated/github.ts.
//
//   npm run github:sync            (unauthenticated: 60 requests/hour)
//   GITHUB_TOKEN=... npm run github:sync
//
// Only repositories marked `visibility: "public"` are queried, so private
// repository names and metadata are never fetched or written. The site reads
// the generated snapshot at build time and never calls GitHub per request.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { projects } from "../src/content/projects.ts";

type RepoSnapshot = {
  pushedAt: string;
  stars: number;
  language: string | null;
  license: string | null;
  archived: boolean;
};

const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
const headers: Record<string, string> = {
  Accept: "application/vnd.github+json",
  "User-Agent": "portfolio-github-sync",
  "X-GitHub-Api-Version": "2022-11-28",
};
if (token) headers.Authorization = `Bearer ${token}`;

const repos: Record<string, RepoSnapshot> = {};
const failures: string[] = [];

for (const project of projects) {
  const repo = project.repository;
  if (!repo || repo.visibility !== "public") continue;
  const key = `${repo.owner}/${repo.name}`;
  const response = await fetch(`https://api.github.com/repos/${key}`, { headers, signal: AbortSignal.timeout(15_000) });
  if (!response.ok) {
    failures.push(`${key}: HTTP ${response.status}`);
    continue;
  }
  const data = (await response.json()) as {
    pushed_at: string;
    stargazers_count: number;
    language: string | null;
    license: { spdx_id?: string } | null;
    archived: boolean;
    private: boolean;
  };
  if (data.private) {
    failures.push(`${key}: repository is private; mark it private in projects.ts`);
    continue;
  }
  repos[key] = {
    pushedAt: data.pushed_at,
    stars: data.stargazers_count,
    language: data.language,
    license: data.license?.spdx_id && data.license.spdx_id !== "NOASSERTION" ? data.license.spdx_id : null,
    archived: data.archived,
  };
}

const output = `// Generated by scripts/sync-github.ts — do not edit by hand.
// Public repository metadata only. Regenerate with \`npm run github:sync\`.
export type RepoSnapshot = {
  pushedAt: string;
  stars: number;
  language: string | null;
  license: string | null;
  archived: boolean;
};

export const githubSnapshot: { generatedAt: string; repos: Record<string, RepoSnapshot> } = ${JSON.stringify(
  { generatedAt: new Date().toISOString(), repos },
  null,
  2,
)};
`;

const target = fileURLToPath(new URL("../src/content/generated/github.ts", import.meta.url));
writeFileSync(target, output);
console.log(`GitHub snapshot written: ${Object.keys(repos).length} public repositories.`);
if (failures.length > 0) {
  console.error(`Skipped:\n- ${failures.join("\n- ")}`);
  process.exitCode = 1;
}
